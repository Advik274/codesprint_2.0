#!/usr/bin/env bash
# One-time provisioning for a fresh GCP (Debian/Ubuntu) VM.
# Safe to re-run — every step is idempotent.
#
#   curl -fsSL https://raw.githubusercontent.com/Advik274/codesprint_2.0/master/deploy/setup-gcp-vm.sh | bash
# or, once the repo is cloned:
#   bash deploy/setup-gcp-vm.sh
set -euo pipefail

REPO_URL="${REPO_URL:-https://github.com/Advik274/codesprint_2.0.git}"
APP_DIR="${APP_DIR:-$HOME/dominance}"
SERVICE="${SERVICE:-dominance}"
PORT="${PORT:-80}"
NODE_MAJOR=20

say() { printf '\n\033[1;33m▸ %s\033[0m\n' "$*"; }
ok()  { printf '\033[0;32m  ✓ %s\033[0m\n' "$*"; }

# ── 1. System packages ────────────────────────────────────────────
say "Installing Node ${NODE_MAJOR} and git"
if ! command -v node >/dev/null 2>&1 || [ "$(node -v | cut -c2- | cut -d. -f1)" -lt "$NODE_MAJOR" ]; then
  curl -fsSL "https://deb.nodesource.com/setup_${NODE_MAJOR}.x" | sudo -E bash -
  sudo apt-get install -y nodejs
fi
sudo apt-get install -y git >/dev/null
ok "node $(node -v), npm $(npm -v), git $(git --version | awk '{print $3}')"

# ── 2. Code ───────────────────────────────────────────────────────
if [ -d "$APP_DIR/.git" ]; then
  say "Updating existing checkout at $APP_DIR"
  git -C "$APP_DIR" fetch --all --quiet
  git -C "$APP_DIR" reset --hard origin/master --quiet
else
  say "Cloning into $APP_DIR"
  git clone --quiet "$REPO_URL" "$APP_DIR"
fi
ok "at commit $(git -C "$APP_DIR" rev-parse --short HEAD)"

# ── 3. Credentials ────────────────────────────────────────────────
# Never leave the built-in fallback password on a public VM.
ENV_FILE="$APP_DIR/server/.env"
if [ ! -f "$ENV_FILE" ]; then
  say "Generating credentials"
  ADMIN_PW="$(openssl rand -base64 12 | tr -d '/+=' | cut -c1-14)"
  ZONE_PW="$(openssl rand -base64 12 | tr -d '/+=' | cut -c1-14)"
  cat > "$ENV_FILE" <<EOF
# Generated by deploy/setup-gcp-vm.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ)
ADMIN_PASSWORD=$ADMIN_PW
ZONE_PASSWORD=$ZONE_PW
PORT=$PORT
NODE_ENV=production
EOF
  chmod 600 "$ENV_FILE"
  ok "wrote $ENV_FILE (chmod 600)"
  NEW_CREDS=1
else
  ok "keeping existing $ENV_FILE"
  NEW_CREDS=0
fi

# ── 4. Build ──────────────────────────────────────────────────────
say "Installing dependencies and building the client"
(cd "$APP_DIR/server" && npm install --omit=dev --no-audit --no-fund --silent)
(cd "$APP_DIR/client" && npm install --no-audit --no-fund --silent && npm run build --silent)
ok "client built to client/dist"

# ── 5. systemd service ────────────────────────────────────────────
# WorkingDirectory must be server/ — the DB path is relative to it.
# CAP_NET_BIND_SERVICE lets a non-root process bind port 80, which
# avoids both running as root and needing nginx in front.
say "Installing systemd service '$SERVICE'"
sudo tee "/etc/systemd/system/${SERVICE}.service" >/dev/null <<EOF
[Unit]
Description=DOMINANCE event server
After=network.target

[Service]
Type=simple
User=$USER
WorkingDirectory=$APP_DIR/server
EnvironmentFile=$APP_DIR/server/.env
ExecStart=$(command -v node) index.js
Restart=always
RestartSec=3
AmbientCapabilities=CAP_NET_BIND_SERVICE
StandardOutput=journal
StandardError=journal

[Install]
WantedBy=multi-user.target
EOF
sudo systemctl daemon-reload
sudo systemctl enable --now "$SERVICE" >/dev/null 2>&1 || sudo systemctl restart "$SERVICE"
sleep 3

# ── 6. Verify ─────────────────────────────────────────────────────
say "Checking health"
if curl -fsS --max-time 5 "http://localhost:${PORT}/health" >/dev/null; then
  ok "server is up on port ${PORT}"
else
  echo "  ✗ health check failed — logs:"
  sudo journalctl -u "$SERVICE" -n 30 --no-pager
  exit 1
fi

IP="$(curl -fsS --max-time 5 -H 'Metadata-Flavor: Google' \
  http://metadata.google.internal/computeMetadata/v1/instance/network-interfaces/0/access-configs/0/external-ip 2>/dev/null || echo '<VM-EXTERNAL-IP>')"

cat <<EOF

──────────────────────────────────────────────────────────────
 DOMINANCE is live
──────────────────────────────────────────────────────────────
  Teams / join   http://$IP/
  Register (QR)  http://$IP/register
  Admin          http://$IP/admin
  Spectator      http://$IP/spectator
EOF

if [ "$NEW_CREDS" = "1" ]; then
cat <<EOF

  ADMIN PASSWORD   $ADMIN_PW
  ZONE PASSWORD    $ZONE_PW
  ^ save these now — they are stored only in server/.env on this VM
EOF
fi

cat <<EOF

  Deploy a change   cd $APP_DIR && ./deploy/update.sh
  Live logs         sudo journalctl -u $SERVICE -f
  Restart           sudo systemctl restart $SERVICE

  If the page does not load, open the firewall (run on your laptop):
    gcloud compute firewall-rules create dominance-http \\
      --allow tcp:${PORT} --target-tags=dominance --description="DOMINANCE event"
    gcloud compute instances add-tags <INSTANCE_NAME> --tags=dominance --zone=<ZONE>
──────────────────────────────────────────────────────────────
EOF
